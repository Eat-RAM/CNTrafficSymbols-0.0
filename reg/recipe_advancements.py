def make_advancement(recipe_id: str, item_id: str) -> Any:
    item_short: str = item_id.split(":")[-1]
    return {
        "parent": "minecraft:recipes/root",
        "criteria": {
            f"has_{item_short}": {
                "conditions": CompactDict({"items": [{"items": [item_id]}]}),
                "trigger": "minecraft:inventory_changed"
            },
            "has_the_recipe": {
                "conditions":
                CompactDict({"recipe": f"cntrafficsymbols_0d0:{recipe_id}"}),
                "trigger": "minecraft:recipe_unlocked"
            }
        },
        "requirements": [
            [
                "has_the_recipe",
                f"has_{item_short}"
            ]
        ],
        "rewards": CompactDict({
            "recipes": [f"cntrafficsymbols_0d0:{recipe_id}"]
        }),
        "sends_telemetry_event": False
    }


def main(argv: Optional[List[str]] = None) -> None:
    parser: ArgumentParser = create_parser("Generate all recipe advancements")
    args: Namespace = parser.parse_args(argv)
    ensure_output_dir(args.dir, args.dry_run)

    for recipe_id, item_id in RECIPES_TO_ITEMS.items():
        to_write = make_advancement(
            recipe_id,
            item_id if ":" in item_id else "cntrafficsymbols_0d0:"+item_id
        )
        write_json_idempotent(args.dir, f"{recipe_id}.json", to_write,
                              args.dry_run, compact=True)


if __name__ == "__main__":
    main()
